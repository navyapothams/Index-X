\set ON_ERROR_STOP on
\timing on
\echo 'IndexX deterministic dataset generation; Flyway schema is not modified.'

-- Prevent accidental duplicate runs. Run in a disposable, migrated development DB.
SELECT EXISTS (
    SELECT 1 FROM products
     WHERE sku LIKE :'seed_prefix' || '-P-%'
) AS seed_already_present \gset
\if :seed_already_present
    \echo 'Seed data with this prefix already exists. Use a fresh disposable database; this script never deletes rows.'
    \quit 3
\endif

BEGIN;
SET LOCAL synchronous_commit = off;
SET LOCAL statement_timeout = 0;
SELECT pg_advisory_xact_lock(hashtext('indexx-deterministic-seed'));

-- The required business roles are seeded by V1. Ensure they exist on upgraded DBs too.
INSERT INTO roles (name)
VALUES ('ADMIN'), ('INVENTORY_MANAGER'), ('SALES_STAFF'), ('PURCHASE_MANAGER')
ON CONFLICT (name) DO NOTHING;

INSERT INTO categories (name, description)
SELECT 'IndexX ' || :'seed_prefix' || ' Category ' || LPAD(n::text, 3, '0'),
       'Generated development category ' || n
  FROM GENERATE_SERIES(1, :category_count) AS g(n);

INSERT INTO subcategories (category_id, name)
SELECT c.id, 'IndexX ' || :'seed_prefix' || ' Segment ' || s.segment_no
 FROM GENERATE_SERIES(1, :category_count) AS cnum(n)
 CROSS JOIN GENERATE_SERIES(1, (:subcategory_count / :category_count)) AS seg(segment_no)
  JOIN categories c
    ON c.name = 'IndexX ' || :'seed_prefix' || ' Category ' || LPAD(cnum.n::text, 3, '0');

INSERT INTO brands (name)
SELECT 'IndexX ' || :'seed_prefix' || ' Brand ' || LPAD(n::text, 4, '0')
  FROM GENERATE_SERIES(1, :brand_count) AS g(n);

INSERT INTO suppliers (name, email, phone, active)
SELECT 'Harborline ' || :'seed_prefix' || ' Supply ' || LPAD(n::text, 5, '0'),
       LOWER(:'seed_prefix') || '.supplier.' || LPAD(n::text, 5, '0') || '@example.invalid',
       '+1-555-' || LPAD((1000000 + n)::text, 7, '0'), TRUE
  FROM GENERATE_SERIES(1, :supplier_count) AS g(n);

INSERT INTO customers (name, email, phone)
SELECT (ARRAY['Avery','Jordan','Morgan','Riley','Casey','Taylor','Quinn','Cameron',
              'Jamie','Drew','Reese','Parker','Rowan','Skyler','Emerson','Dakota']
       )[1 + MOD(n * 7, 16)] || ' ' ||
       (ARRAY['Shah','Patel','Rao','Mehta','Singh','Nair','Iyer','Kapoor',
              'Das','Khan','Menon','Reddy','Joshi','Bose','Verma','Ghosh']
       )[1 + MOD(n * 11, 16)],
       LOWER(:'seed_prefix') || '.customer.' || LPAD(n::text, 8, '0') || '@example.invalid',
       '+1-555-' || LPAD((2000000 + n)::text, 7, '0')
  FROM GENERATE_SERIES(1, :customer_count) AS g(n);

INSERT INTO warehouses (code, name, active)
SELECT :'seed_prefix' || '-WH-' || LPAD(n::text, 3, '0'),
       'IndexX ' || :'seed_prefix' || ' Distribution Center ' || LPAD(n::text, 2, '0'), TRUE
  FROM GENERATE_SERIES(1, :warehouse_count) AS g(n);

-- Seed-only accounts are inactive and have no usable credentials.
INSERT INTO users (email, password_hash, display_name, active)
SELECT LOWER(:'seed_prefix') || '.' || LOWER(role_name) || '@example.invalid',
       'DISABLED_DEVELOPMENT_SEED_ACCOUNT',
       'Seed ' || role_name, FALSE
  FROM (VALUES ('ADMIN'), ('INVENTORY_MANAGER'), ('SALES_STAFF'), ('PURCHASE_MANAGER')) AS r(role_name)
ON CONFLICT (email) DO NOTHING;

INSERT INTO user_roles (user_id, role_id)
SELECT u.id, r.id
  FROM (VALUES ('ADMIN'), ('INVENTORY_MANAGER'), ('SALES_STAFF'), ('PURCHASE_MANAGER')) AS wanted(role_name)
  JOIN roles r ON r.name = wanted.role_name
  JOIN users u ON u.email = LOWER(:'seed_prefix') || '.' || LOWER(wanted.role_name) || '@example.invalid'
ON CONFLICT DO NOTHING;

CREATE TEMP TABLE seed_products (
    product_no INTEGER PRIMARY KEY,
    product_id BIGINT NOT NULL UNIQUE
) ON COMMIT DROP;

INSERT INTO products (sku, name, description, category_id, subcategory_id, brand_id,
                      selling_price, cost_price, reorder_level, active)
SELECT :'seed_prefix' || '-P-' || LPAD(n::text, 8, '0'),
       (ARRAY['Industrial fastener','Storage tote','Safety glove','Packing tape',
              'Cable organizer','LED work lamp','Shipping carton','Precision driver',
              'Protective eyewear','Utility knife','Steel bracket','Label roll']
       )[1 + MOD(n * 13, 12)] || ' ' || LPAD(n::text, 5, '0'),
       'Deterministic demo product ' || n || '; generated by the IndexX seed mechanism.',
       c.id, sc.id, b.id,
       ROUND((10 + MOD(n * 379, 25000) / 100.0)::numeric, 2),
       ROUND(((10 + MOD(n * 379, 25000) / 100.0) * (0.45 + MOD(n, 30) / 100.0))::numeric, 2),
       5 + MOD(n * 3, 16), (MOD(n, 50) <> 0)
  FROM GENERATE_SERIES(1, :product_count) AS g(n)
  JOIN categories c
    ON c.name = 'IndexX ' || :'seed_prefix' || ' Category ' ||
                LPAD((1 + ((n - 1) / (:product_count / :category_count)))::text, 3, '0')
  JOIN subcategories sc
    ON sc.category_id = c.id
   AND sc.name = 'IndexX ' || :'seed_prefix' || ' Segment ' ||
                 (1 + MOD(n - 1, (:subcategory_count / :category_count)))
  JOIN brands b
    ON b.name = 'IndexX ' || :'seed_prefix' || ' Brand ' || LPAD((1 + MOD(n * 37, :brand_count))::text, 4, '0');

INSERT INTO seed_products (product_no, product_id)
SELECT n, p.id
  FROM GENERATE_SERIES(1, :product_count) AS g(n)
  JOIN products p ON p.sku = :'seed_prefix' || '-P-' || LPAD(n::text, 8, '0');

CREATE TEMP TABLE seed_suppliers (
    supplier_no INTEGER PRIMARY KEY,
    supplier_id BIGINT NOT NULL UNIQUE
) ON COMMIT DROP;
INSERT INTO seed_suppliers
SELECT n, s.id
  FROM GENERATE_SERIES(1, :supplier_count) AS g(n)
  JOIN suppliers s ON s.email = LOWER(:'seed_prefix') || '.supplier.' || LPAD(n::text, 5, '0') || '@example.invalid';

CREATE TEMP TABLE seed_warehouses (
    warehouse_no INTEGER PRIMARY KEY,
    warehouse_id BIGINT NOT NULL UNIQUE
) ON COMMIT DROP;
INSERT INTO seed_warehouses
SELECT n, w.id
  FROM GENERATE_SERIES(1, :warehouse_count) AS g(n)
  JOIN warehouses w ON w.code = :'seed_prefix' || '-WH-' || LPAD(n::text, 3, '0');

CREATE TEMP TABLE seed_customers (
    customer_no INTEGER PRIMARY KEY,
    customer_id BIGINT NOT NULL UNIQUE
) ON COMMIT DROP;
INSERT INTO seed_customers
SELECT n, c.id
  FROM GENERATE_SERIES(1, :customer_count) AS g(n)
  JOIN customers c ON c.email = LOWER(:'seed_prefix') || '.customer.' || LPAD(n::text, 8, '0') || '@example.invalid';

CREATE TEMP TABLE seed_users (
    role_name VARCHAR(40) PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE
) ON COMMIT DROP;
INSERT INTO seed_users
SELECT role_name, u.id
  FROM (VALUES ('ADMIN'), ('INVENTORY_MANAGER'), ('SALES_STAFF'), ('PURCHASE_MANAGER')) AS wanted(role_name)
  JOIN users u ON u.email = LOWER(:'seed_prefix') || '.' || LOWER(wanted.role_name) || '@example.invalid';

-- Every supplier owns a deterministic block of products; this creates a valid M:N catalog.
INSERT INTO supplier_products (supplier_id, product_id, supplier_product_code,
                               supplier_price, lead_time_days, preferred)
SELECT ss.supplier_id, sp.product_id,
       :'seed_prefix' || '-SUP-' || LPAD(ss.supplier_no::text, 5, '0') ||
       '-P-' || LPAD(sp.product_no::text, 8, '0'),
       ROUND(p.cost_price * (1 + MOD(sp.product_no, 9) / 100.0), 2),
       3 + MOD(sp.product_no * 7, 25), (MOD(sp.product_no, 10) = 0)
  FROM seed_products sp
  JOIN seed_suppliers ss
    ON ss.supplier_no = 1 + ((sp.product_no - 1) / (:product_count / :supplier_count))
  JOIN products p ON p.id = sp.product_id;

-- Purchase volume covers each generated product/warehouse pair before sales are posted.
CREATE TEMP TABLE seed_purchase_orders (
    order_no INTEGER PRIMARY KEY,
    purchase_order_id BIGINT NOT NULL UNIQUE
) ON COMMIT DROP;
WITH inserted AS (
    INSERT INTO purchase_orders (order_number, supplier_id, warehouse_id, created_by,
                                 status, order_date, expected_date, notes)
    SELECT :'seed_prefix' || '-PO-' || LPAD(g.n::text, 8, '0'),
           ss.supplier_id, sw.warehouse_id, su.user_id, 'DRAFT',
           TIMESTAMPTZ '2026-10-01 10:00:00+00' - (MOD(g.n * 17, 730) || ' days')::interval,
           (DATE '2026-10-01' - MOD(g.n * 17, 730) + 7),
           'Deterministic generated purchase order'
      FROM GENERATE_SERIES(1, :purchase_order_count) AS g(n)
      JOIN seed_suppliers ss
        ON ss.supplier_no = 1 + ((g.n - 1) / (:warehouse_count * ((:product_count / :supplier_count) / 4)))
      JOIN seed_warehouses sw
        ON sw.warehouse_no = 1 + MOD(((g.n - 1) % (:warehouse_count * ((:product_count / :supplier_count) / 4))), :warehouse_count)
      JOIN seed_users su ON su.role_name = 'PURCHASE_MANAGER'
    RETURNING id, order_number
)
INSERT INTO seed_purchase_orders (order_no, purchase_order_id)
SELECT RIGHT(order_number, 8)::integer, id FROM inserted;

INSERT INTO purchase_order_items (purchase_order_id, product_id, quantity_ordered, quantity_received, unit_cost)
SELECT spo.purchase_order_id, sp.product_id,
       12 + MOD(spo.order_no * 3 + line_no * 7, 25), 0, supplier_product.supplier_price
  FROM seed_purchase_orders spo
 CROSS JOIN GENERATE_SERIES(0, 3) AS line(line_no)
  JOIN seed_suppliers ss
    ON ss.supplier_no = 1 + ((spo.order_no - 1) / (:warehouse_count * ((:product_count / :supplier_count) / 4)))
  JOIN seed_products sp
    ON sp.product_no = ((ss.supplier_no - 1) * (:product_count / :supplier_count)) +
       MOD((((spo.order_no - 1) % (:warehouse_count * ((:product_count / :supplier_count) / 4))) / :warehouse_count) * 4 + line.line_no,
           (:product_count / :supplier_count)) + 1
  JOIN supplier_products supplier_product
    ON supplier_product.supplier_id = ss.supplier_id AND supplier_product.product_id = sp.product_id;

-- Orders follow the legal workflow. A small share are partially received or cancelled after
-- a partial receipt; the half receipt still leaves stock for the matching generated sale.
UPDATE purchase_orders po SET status = 'ORDERED'
  FROM seed_purchase_orders seed WHERE po.id = seed.purchase_order_id;
UPDATE purchase_order_items poi
   SET quantity_received = CASE WHEN MOD(seed.order_no, 20) = 0
                                THEN GREATEST(1, quantity_ordered / 2)
                                ELSE quantity_ordered END
  FROM seed_purchase_orders seed
  JOIN purchase_orders po ON po.id = seed.purchase_order_id AND po.status = 'ORDERED'
 WHERE poi.purchase_order_id = po.id;
UPDATE purchase_orders po SET status = 'CANCELLED'
  FROM seed_purchase_orders seed
 WHERE po.id = seed.purchase_order_id
   AND po.status = 'PARTIALLY_RECEIVED' AND MOD(seed.order_no, 100) = 0;

-- Two SKUs per sale, one warehouse per order. The sequence covers every generated stock pair.
CREATE TEMP TABLE seed_sales_orders (
    order_no INTEGER PRIMARY KEY,
    sales_order_id BIGINT NOT NULL UNIQUE
) ON COMMIT DROP;
WITH inserted AS (
    INSERT INTO sales_orders (order_number, customer_id, warehouse_id, created_by,
                              status, order_date, notes)
    SELECT :'seed_prefix' || '-SO-' || LPAD(g.n::text, 8, '0'),
           sc.customer_id, sw.warehouse_id, su.user_id, 'DRAFT',
           TIMESTAMPTZ '2026-10-01 18:00:00+00' - (MOD(g.n * 23, 730) || ' days')::interval,
           'Deterministic generated sales order'
      FROM GENERATE_SERIES(1, :sales_order_count) AS g(n)
      JOIN seed_customers sc ON sc.customer_no = 1 + MOD(g.n * 97, :customer_count)
      JOIN seed_warehouses sw ON sw.warehouse_no = 1 + MOD(g.n - 1, :warehouse_count)
      JOIN seed_users su ON su.role_name = 'SALES_STAFF'
    RETURNING id, order_number
)
INSERT INTO seed_sales_orders (order_no, sales_order_id)
SELECT RIGHT(order_number, 8)::integer, id FROM inserted;

INSERT INTO sales_order_items (sales_order_id, product_id, quantity, unit_price, discount_rate)
SELECT sso.sales_order_id, sp.product_id,
       1 + MOD(sso.order_no * 7 + item.line_no * 3, 3), p.selling_price,
       (MOD(sso.order_no * 13 + item.line_no * 17, 101) / 1000.0)::numeric(5,4)
  FROM seed_sales_orders sso
 CROSS JOIN GENERATE_SERIES(0, 1) AS item(line_no)
  JOIN seed_products sp
    ON sp.product_no = (((sso.order_no - 1) / :warehouse_count) * 2) + item.line_no + 1
  JOIN products p ON p.id = sp.product_id;

-- 90% complete (stock is posted by V3), 5% cancelled, 5% remain as open drafts.
UPDATE sales_orders so SET status = CASE WHEN MOD(seed.order_no, 20) < 18 THEN 'COMPLETED' ELSE 'CANCELLED' END
  FROM seed_sales_orders seed
 WHERE so.id = seed.sales_order_id AND MOD(seed.order_no, 20) <> 19;

-- One settled payment for each completed order, calculated from its immutable line snapshots.
INSERT INTO payments (sales_order_id, amount, payment_method, status, payment_reference, paid_at)
SELECT so.id,
       ROUND(SUM(soi.quantity * soi.unit_price * (1 - soi.discount_rate)), 2),
       (ARRAY['CARD','UPI','CASH','BANK_TRANSFER','OTHER'])[1 + MOD(seed.order_no, 5)],
       'COMPLETED', :'seed_prefix' || '-PAY-' || LPAD(seed.order_no::text, 8, '0'),
       so.order_date + INTERVAL '1 hour'
  FROM seed_sales_orders seed
  JOIN sales_orders so ON so.id = seed.sales_order_id AND so.status = 'COMPLETED'
  JOIN sales_order_items soi ON soi.sales_order_id = so.id
 GROUP BY seed.order_no, so.id, so.order_date;

-- A small set of valid customer and supplier returns exercises return workflow triggers.
CREATE TEMP TABLE seed_returns (return_no INTEGER PRIMARY KEY, return_id BIGINT NOT NULL UNIQUE) ON COMMIT DROP;
WITH inserted AS (
    INSERT INTO returns (return_number, return_type, sales_order_id, requested_by, status, reason, requested_at)
    SELECT :'seed_prefix' || '-CR-' || LPAD(seed.order_no::text, 8, '0'), 'CUSTOMER', so.id,
           su.user_id, 'REQUESTED', 'Generated customer return: unopened item',
           so.order_date + INTERVAL '4 days'
      FROM seed_sales_orders seed
      JOIN sales_orders so ON so.id = seed.sales_order_id AND so.status = 'COMPLETED'
      JOIN seed_users su ON su.role_name = 'SALES_STAFF'
     WHERE MOD(seed.order_no, 25) = 0
    RETURNING id, return_number
)
INSERT INTO seed_returns SELECT RIGHT(return_number, 8)::integer, id FROM inserted;

INSERT INTO return_items (return_id, sales_order_item_id, quantity, disposition)
SELECT sr.return_id, soi.id, 1, 'RESTOCK'
  FROM seed_returns sr
  JOIN seed_sales_orders seed ON seed.order_no = sr.return_no
  JOIN sales_order_items soi ON soi.sales_order_id = seed.sales_order_id
  JOIN seed_products sp ON sp.product_id = soi.product_id
 WHERE sp.product_no = (((seed.order_no - 1) / :warehouse_count) * 2) + 1;
UPDATE returns SET status = 'APPROVED' WHERE return_number LIKE :'seed_prefix' || '-CR-%';
UPDATE returns SET status = 'COMPLETED' WHERE return_number LIKE :'seed_prefix' || '-CR-%';

WITH inserted AS (
    INSERT INTO returns (return_number, return_type, purchase_order_id, requested_by,
                         status, reason, requested_at)
    SELECT :'seed_prefix' || '-SR-' || LPAD(seed.order_no::text, 8, '0'), 'SUPPLIER', po.id,
           su.user_id, 'REQUESTED', 'Generated supplier return: quality defect',
           po.order_date + INTERVAL '3 days'
      FROM seed_purchase_orders seed
      JOIN purchase_orders po ON po.id = seed.purchase_order_id AND po.status = 'RECEIVED'
      JOIN seed_users su ON su.role_name = 'PURCHASE_MANAGER'
     WHERE MOD(seed.order_no, 50) = 0
    RETURNING id, return_number
)
INSERT INTO seed_returns
SELECT RIGHT(return_number, 8)::integer + :purchase_order_count + :sales_order_count + 1, id FROM inserted;

INSERT INTO return_items (return_id, purchase_order_item_id, quantity, disposition)
SELECT sr.return_id, poi.id, 1, 'RETURN_TO_SUPPLIER'
  FROM seed_returns sr
  JOIN seed_purchase_orders seed
    ON sr.return_no > (:purchase_order_count + :sales_order_count)
   AND seed.order_no = sr.return_no - :purchase_order_count - :sales_order_count - 1
  JOIN purchase_order_items poi ON poi.purchase_order_id = seed.purchase_order_id
  JOIN seed_products sp ON sp.product_id = poi.product_id
 WHERE sp.product_no = ((1 + ((seed.order_no - 1) / (:warehouse_count * ((:product_count / :supplier_count) / 4)))) - 1)
       * (:product_count / :supplier_count)
       + MOD((((seed.order_no - 1) % (:warehouse_count * ((:product_count / :supplier_count) / 4))) / :warehouse_count) * 4,
             (:product_count / :supplier_count)) + 1;
UPDATE returns SET status = 'APPROVED' WHERE return_number LIKE :'seed_prefix' || '-SR-%';
UPDATE returns SET status = 'COMPLETED' WHERE return_number LIKE :'seed_prefix' || '-SR-%';

INSERT INTO product_reviews (product_id, customer_id, rating, title, review_text, status, created_at)
SELECT sp.product_id, sc.customer_id, 1 + MOD(g.n * 13, 5),
       (ARRAY['Reliable','Good value','As described','Would buy again','Solid quality'])[1 + MOD(g.n, 5)],
       'Generated review ' || g.n || ': consistent fit and expected performance.',
       CASE WHEN MOD(g.n, 10) < 8 THEN 'PUBLISHED' WHEN MOD(g.n, 10) = 8 THEN 'PENDING' ELSE 'HIDDEN' END,
       TIMESTAMPTZ '2026-10-01 12:00:00+00' - (MOD(g.n * 19, 1095) || ' days')::interval
  FROM GENERATE_SERIES(1, :review_count) AS g(n)
  JOIN seed_products sp ON sp.product_no = 1 + MOD((g.n - 1) * 73, :product_count)
  JOIN seed_customers sc ON sc.customer_no = 1 + ((g.n - 1) / 5);

INSERT INTO search_history (user_id, query_text, product_id, searched_at)
SELECT su.user_id,
       (ARRAY['industrial fastener','storage tote','safety glove','packing tape',
              'work lamp','shipping carton','utility knife','bulk supplies'])[1 + MOD(g.n * 11, 8)],
       CASE WHEN MOD(g.n, 4) = 0 THEN NULL ELSE sp.product_id END,
       TIMESTAMPTZ '2026-10-01 20:00:00+00' - (MOD(g.n * 29, 730) || ' days')::interval
  FROM GENERATE_SERIES(1, :search_count) AS g(n)
  JOIN seed_products sp ON sp.product_no = 1 + MOD(g.n * 97, :product_count)
  JOIN seed_users su ON su.role_name = CASE MOD(g.n, 4)
       WHEN 0 THEN 'ADMIN' WHEN 1 THEN 'INVENTORY_MANAGER'
       WHEN 2 THEN 'SALES_STAFF' ELSE 'PURCHASE_MANAGER' END;

