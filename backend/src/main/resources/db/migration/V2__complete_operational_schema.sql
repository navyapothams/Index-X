CREATE INDEX idx_user_roles_role ON user_roles (role_id, user_id);

CREATE TABLE supplier_products (
    supplier_id BIGINT NOT NULL REFERENCES suppliers(id) ON DELETE RESTRICT,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    supplier_product_code VARCHAR(80),
    supplier_price NUMERIC(12,2) NOT NULL CHECK (supplier_price >= 0),
    lead_time_days INTEGER NOT NULL DEFAULT 0 CHECK (lead_time_days >= 0),
    preferred BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (supplier_id, product_id)
);
CREATE UNIQUE INDEX uq_supplier_products_supplier_code
    ON supplier_products (supplier_id, supplier_product_code)
    WHERE supplier_product_code IS NOT NULL;
CREATE INDEX idx_supplier_products_product ON supplier_products (product_id, supplier_id);

CREATE TABLE purchase_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(40) NOT NULL UNIQUE,
    supplier_id BIGINT NOT NULL REFERENCES suppliers(id) ON DELETE RESTRICT,
    warehouse_id BIGINT NOT NULL REFERENCES warehouses(id) ON DELETE RESTRICT,
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN ('DRAFT','ORDERED','PARTIALLY_RECEIVED','RECEIVED','CANCELLED')),
    order_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expected_date DATE,
    received_at TIMESTAMPTZ,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE purchase_order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id BIGINT NOT NULL REFERENCES purchase_orders(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    quantity_ordered INTEGER NOT NULL CHECK (quantity_ordered > 0),
    quantity_received INTEGER NOT NULL DEFAULT 0 CHECK (quantity_received >= 0 AND quantity_received <= quantity_ordered),
    unit_cost NUMERIC(12,2) NOT NULL CHECK (unit_cost >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (purchase_order_id, product_id)
);

CREATE TABLE sales_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(40) NOT NULL UNIQUE,
    customer_id BIGINT REFERENCES customers(id) ON DELETE SET NULL,
    warehouse_id BIGINT NOT NULL REFERENCES warehouses(id) ON DELETE RESTRICT,
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN ('DRAFT','COMPLETED','CANCELLED')),
    order_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE sales_order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sales_order_id BIGINT NOT NULL REFERENCES sales_orders(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    discount_rate NUMERIC(5,4) NOT NULL DEFAULT 0 CHECK (discount_rate >= 0 AND discount_rate <= 1),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (sales_order_id, product_id)
);
CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sales_order_id BIGINT NOT NULL REFERENCES sales_orders(id) ON DELETE RESTRICT,
    amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    payment_method VARCHAR(24) NOT NULL
        CHECK (payment_method IN ('CASH','CARD','BANK_TRANSFER','UPI','OTHER')),
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING','COMPLETED','FAILED','REFUNDED')),
    payment_reference VARCHAR(120),
    paid_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((status = 'COMPLETED' AND paid_at IS NOT NULL) OR status <> 'COMPLETED')
);
CREATE UNIQUE INDEX uq_payments_reference
    ON payments (payment_reference) WHERE payment_reference IS NOT NULL;

CREATE TABLE returns (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_number VARCHAR(40) NOT NULL UNIQUE,
    return_type VARCHAR(12) NOT NULL CHECK (return_type IN ('CUSTOMER','SUPPLIER')),
    sales_order_id BIGINT REFERENCES sales_orders(id) ON DELETE RESTRICT,
    purchase_order_id BIGINT REFERENCES purchase_orders(id) ON DELETE RESTRICT,
    requested_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'REQUESTED'
        CHECK (status IN ('REQUESTED','APPROVED','COMPLETED','REJECTED')),
    reason TEXT,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((return_type = 'CUSTOMER' AND sales_order_id IS NOT NULL AND purchase_order_id IS NULL)
        OR (return_type = 'SUPPLIER' AND purchase_order_id IS NOT NULL AND sales_order_id IS NULL))
);
CREATE TABLE return_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    return_id BIGINT NOT NULL REFERENCES returns(id) ON DELETE CASCADE,
    sales_order_item_id BIGINT REFERENCES sales_order_items(id) ON DELETE RESTRICT,
    purchase_order_item_id BIGINT REFERENCES purchase_order_items(id) ON DELETE RESTRICT,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    disposition VARCHAR(24) NOT NULL
        CHECK (disposition IN ('RESTOCK','WRITE_OFF','RETURN_TO_SUPPLIER')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((sales_order_item_id IS NOT NULL AND purchase_order_item_id IS NULL)
        OR (sales_order_item_id IS NULL AND purchase_order_item_id IS NOT NULL)),
    UNIQUE (return_id, sales_order_item_id),
    UNIQUE (return_id, purchase_order_item_id)
);

CREATE TABLE inventory_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    warehouse_id BIGINT NOT NULL REFERENCES warehouses(id) ON DELETE RESTRICT,
    transaction_type VARCHAR(16) NOT NULL
        CHECK (transaction_type IN ('PURCHASE','SALE','RETURN','ADJUSTMENT')),
    quantity_delta INTEGER NOT NULL CHECK (quantity_delta <> 0),
    purchase_order_id BIGINT REFERENCES purchase_orders(id) ON DELETE RESTRICT,
    sales_order_id BIGINT REFERENCES sales_orders(id) ON DELETE RESTRICT,
    return_id BIGINT REFERENCES returns(id) ON DELETE RESTRICT,
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (
        (transaction_type = 'PURCHASE' AND quantity_delta > 0 AND purchase_order_id IS NOT NULL AND sales_order_id IS NULL AND return_id IS NULL)
        OR (transaction_type = 'SALE' AND quantity_delta < 0 AND sales_order_id IS NOT NULL AND purchase_order_id IS NULL AND return_id IS NULL)
        OR (transaction_type = 'RETURN' AND return_id IS NOT NULL AND purchase_order_id IS NULL AND sales_order_id IS NULL)
        OR (transaction_type = 'ADJUSTMENT' AND purchase_order_id IS NULL AND sales_order_id IS NULL AND return_id IS NULL AND NULLIF(BTRIM(note), '') IS NOT NULL)
    )
);

-- Preserve existing V1 stock while establishing an auditable opening ledger balance.
INSERT INTO inventory_transactions
    (product_id, warehouse_id, transaction_type, quantity_delta, note, created_at)
SELECT product_id, warehouse_id, 'ADJUSTMENT', quantity_on_hand,
       'Opening balance migrated from the V1 inventory balance', updated_at
  FROM inventory
 WHERE quantity_on_hand > 0;

CREATE TABLE product_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
    customer_id BIGINT NOT NULL REFERENCES customers(id) ON DELETE RESTRICT,
    rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    title VARCHAR(160),
    review_text TEXT,
    status VARCHAR(12) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING','PUBLISHED','HIDDEN')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (product_id, customer_id)
);
CREATE TABLE search_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    query_text VARCHAR(250) NOT NULL CHECK (BTRIM(query_text) <> ''),
    product_id BIGINT REFERENCES products(id) ON DELETE SET NULL,
    searched_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    entity_name VARCHAR(80) NOT NULL,
    entity_id VARCHAR(160) NOT NULL,
    action VARCHAR(8) NOT NULL CHECK (action IN ('INSERT','UPDATE','DELETE')),
    old_values JSONB,
    new_values JSONB,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

